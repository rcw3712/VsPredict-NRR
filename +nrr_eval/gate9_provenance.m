function run = gate9_provenance(run, cfg)
% NRR_EVAL.GATE9_PROVENANCE  Corrected canonical-HP holdout evaluation.
% Uses the same scaled-meta API as nested CV and mandatory depth segments.

assert(isfield(run,'canon_hp') && isfield(run,'canon_hp_hash'), ...
    'gate9_provenance: canonical HP must be selected before Gate 9');
hp=run.canon_hp;
T_dev=run.T_A_raw(run.roles.dev_mask,:);
T_hold=run.T_A_raw(run.roles.hold_mask,:);
out3=fullfile(run.folder,'03_models');

pm_dev=nrr_data.fit_pm(T_dev,cfg);
[X_d,y_d]=nrr_data.apply_pm_deploy(T_dev,pm_dev,cfg);
[X_h,y_h]=nrr_data.apply_pm(T_hold,pm_dev,cfg);
inner_f=nrr_data.build_folds(T_dev,cfg.cv.n_inner,cfg);
[oof_m,ledger_oof]=nrr_models.generate_inner_oof(T_dev,inner_f,hp, ...
    cfg.seeds.canonical,0,cfg);
meta_scaler=nrr_models.fit_meta_scaler(oof_m);
oof_sc=nrr_models.apply_meta_scaler(oof_m,meta_scaler);
stacker=nrr_models.fit_ridge_stacker(oof_sc,y_d,hp.ridge_lambda,cfg);
assert(strcmp(stacker.input_space,'standardized_meta'), ...
    'gate9_provenance: stacker input space mismatch');

seg_dev=nrr_data.depth_segment_ids(T_dev.(cfg.data.depth_col),cfg);
seg_hold=nrr_data.depth_segment_ids(T_hold.(cfg.data.depth_col),cfg);
[base_nets,ledger_fit]=nrr_models.fit_base_set(X_d,y_d,hp, ...
    cfg.seeds.canonical,0,cfg,seg_dev);
[meta_h,pred_audit]=nrr_models.predict_base_set(base_nets,X_h,seg_hold);
y_pred=nrr_models.predict_ridge_stacker(stacker, ...
    nrr_models.apply_meta_scaler(meta_h,meta_scaler));
assert(all(isfinite(y_pred)) && numel(y_pred)==height(T_hold), ...
    'gate9_provenance: holdout prediction incomplete');

cfg_dr=cfg; cfg_dr.dr.train_n=height(T_dev);
dr=nrr_models.fit_direct_ridge(X_d,y_d,cfg.dr.lambda,cfg_dr);
y_dr=X_h*dr.B+dr.b0;

names=["PNN";"MLFFNN";"DFFNN";"CNN1D";"Ridge_stacker";"Direct_Ridge"];
status=[repmat("PRESPECIFIED_BASE",4,1);"PRESPECIFIED_PRIMARY"; ...
    "POST_HOC_EXPLORATORY_392_ONLY"];
P=[meta_h y_pred y_dr]; M=repmat(nrr_eval.metrics(y_h,P(:,1)),6,1);
for j=1:6; M(j)=nrr_eval.metrics(y_h,P(:,j)); end
Tm=table(names,status,[M.n]',[M.r2]',[M.rmse]',[M.mae]',[M.bias]', ...
    'VariableNames',{'MODEL','STATUS','N','R2','RMSE','MAE','BIAS'});
writetable(Tm,fullfile(out3,'CORRECTED_HOLDOUT_MODEL_METRICS.csv'));
writetable(table(T_hold.(cfg.data.id_col),T_hold.(cfg.data.depth_col),y_h, ...
    P(:,1),P(:,2),P(:,3),P(:,4),y_pred,y_dr, ...
    'VariableNames',{'ROW_ID','DEPTH','VS_MEASURED','PRED_PNN', ...
    'PRED_MLFFNN','PRED_DFFNN','PRED_CNN1D','PRED_RIDGE_STACKER', ...
    'PRED_DIRECT_RIDGE'}), ...
    fullfile(out3,'CORRECTED_HOLDOUT_ROW_PREDICTIONS.csv'));
writetable(pred_audit,fullfile(out3,'CORRECTED_HOLDOUT_CNN_PREDICTION_AUDIT.csv'));
ledger_fit.OUTER_FOLD=zeros(height(ledger_fit),1);
ledger_fit.INNER_FOLD=zeros(height(ledger_fit),1);
ledger_fit.PRED_RETAINED_CROSS_SEGMENT=zeros(height(ledger_fit),1);
ledger=[ledger_oof;ledger_fit];
writetable(ledger,fullfile(out3,'CORRECTED_HOLDOUT_CNN_TRAINING_LEDGER.csv'));
assert(all(ledger.N_RETAINED_CROSS_SEGMENT==0) && ...
    pred_audit.N_RETAINED_CROSS_SEGMENT==0, ...
    'gate9_provenance: cross-segment CNN window retained');

provenance='PED_CORRECTED_FULL_REANALYSIS';
if isfield(run,'provenance'); provenance=run.provenance; end
m=M(5); mdr=M(6);
writetable(table("ridge_stacker",string(provenance),m.r2,m.rmse,m.mae,m.bias, ...
    "LEGACY_INVALID_RAW_META_SCALING",-3.0622,run.canon_hp.pnn_spread, ...
    run.canon_hp.ridge_lambda, ...
    'VariableNames',{'MODEL','PROVENANCE_CLASS','HOLDOUT_R2','HOLDOUT_RMSE', ...
    'HOLDOUT_MAE','HOLDOUT_BIAS','LEGACY_STATUS','LEGACY_R2', ...
    'CANONICAL_PNN_SPREAD','CANONICAL_RIDGE_LAMBDA'}), ...
    fullfile(out3,'HISTORICAL_PROVENANCE_STATUS.csv'));

run.hist=struct('model','ridge_stacker','holdout_r2',m.r2, ...
    'holdout_metrics',m,'direct_ridge',mdr,'hp',hp, ...
    'provenance',provenance,'legacy_r2',-3.0622, ...
    'legacy_status','LEGACY_INVALID_RAW_META_SCALING', ...
    'selection_set',sprintf('holdout_fold_%d_n%d', ...
        cfg.cv.holdout_fold,run.n_hold),'predictions',P, ...
    'prediction_table_file','CORRECTED_HOLDOUT_ROW_PREDICTIONS.csv');
run.gate.GATE_9='PASS';
fprintf('[G9] PASS - canonical HP spread=%.2f lambda=%.4f | holdout R2=%.4f | DR=%.4f\n', ...
    hp.pnn_spread,hp.ridge_lambda,m.r2,mdr.r2);
end
